GLYPHS[chr(0xFD)] = GLYPHS['I']

# ASCII kodlarina gore sirala (0-127 arasinda tanimli olanlari yaz,
# tanimsizlari bos/space yap)
import sys

out = []
out.append("#ifndef OTUKENOS_FONT8X8_H")
out.append("#define OTUKENOS_FONT8X8_H")
out.append("#include <stdint.h>")
out.append("/* otukenOS-mini icin elle tasarlanmis 8x8 bitmap font.")
out.append(" * 0-127: ASCII. 128-255: ISO-8859-9 (Turkce) harfleri. */")
out.append("static const uint8_t font8x8[256][8] = {")

for code in range(256):
    ch = chr(code)
    if ch == 'i':
        # Turkce'de noktali/noktasiz i ayrimi kritik oldugu icin kucuk
        # 'i' burada genel "kucuge katla" kuralindan istisna tutulur.
        rows = GLYPHS['i_dotted_lower']
    else:
        rows = GLYPHS.get(ch.upper() if ch.isalpha() and code < 128 else ch, GLYPHS.get(ch, GLYPHS[' ']))
    bytes_ = []
    for row in rows:
        b = 0
        for i, c in enumerate(row):
            if c == '#':
                b |= (1 << (7 - i))
        bytes_.append(b)
    hexvals = ", ".join("0x%02X" % b for b in bytes_)
    label = ch if (ch.isprintable() and code < 128) else ("TR-%02X" % code)
    out.append("    [%d] = {%s}, /* '%s' */" % (code, hexvals, label))

out.append("};")
out.append("#endif")

with open("include/font8x8.h", "w") as f:
    f.write("\n".join(out) + "\n")

print("font8x8.h uretildi,", len(GLYPHS), "glif tanimlandi")
