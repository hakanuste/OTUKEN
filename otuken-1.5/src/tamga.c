/* =====================================================================
 * VEKTÖR TARAYICI
 * Nonzero winding kuralı. Dikeyde ALT_ORNEK kez alt-örnekleme,
 * yatayda analitik kaplama: kenarlar basamaklı görünmez.
 * Tamamen tamsayı; koordinatlar 8.8 sabit noktada tutulur.
 * ===================================================================== */

#define ALT_ORNEK   4
#define SABIT       8                      /* 8.8 sabit nokta */
#define SB(v)       ((int32_t)(v) << SABIT)

static uint8_t g_kaplama[TAMGA_AZAMI * TAMGA_AZAMI];

typedef struct { int32_t x; int8_t yon; } kesim_t;

/* Rengi aydinlatir (miktar>0) ya da karartir (miktar<0). -255..255 */
uint32_t tamga_ton(uint32_t renk, int miktar) {
    int r = (int)((renk >> 16) & 0xFF), g = (int)((renk >> 8) & 0xFF), b = (int)(renk & 0xFF);
    if (miktar > 0) {
        r += (255 - r) * miktar / 255;
        g += (255 - g) * miktar / 255;
        b += (255 - b) * miktar / 255;
    } else {
        r += r * miktar / 255;
        g += g * miktar / 255;
        b += b * miktar / 255;
    }
    if (r < 0) r = 0;
    if (r > 255) r = 255;
    if (g < 0) g = 0;
    if (g > 255) g = 255;
    if (b < 0) b = 0;
    if (b > 255) b = 255;
    return ((uint32_t)r << 16) | ((uint32_t)g << 8) | (uint32_t)b;
}

static uint32_t harman(uint32_t zem, uint32_t on, int a /* 0..255 */) {
    if (a >= 255) return on;
    if (a <= 0)   return zem;
    int zr = (int)((zem >> 16) & 0xFF), zg = (int)((zem >> 8) & 0xFF), zb = (int)(zem & 0xFF);
    int orr = (int)((on >> 16) & 0xFF), og = (int)((on >> 8) & 0xFF), ob = (int)(on & 0xFF);
    int r = (zr * (255 - a) + orr * a) / 255;
    int g = (zg * (255 - a) + og  * a) / 255;
    int b = (zb * (255 - a) + ob  * a) / 255;
    return ((uint32_t)r << 16) | ((uint32_t)g << 8) | (uint32_t)b;
}

/* Bir katmanın kaplamasını g_kaplama'ya yazar (0..255). */
static void katman_tara(const tamga_t *t, int katman, int boy) {
    for (int i = 0; i < boy * boy; i++) g_kaplama[i] = 0;

    const int pay = ALT_ORNEK;
    kesim_t kes[64];

    for (int sy = 0; sy < boy * pay; sy++) {
        /* alt-tarama satırının y'si, 8.8 sabit noktada */
        int32_t yy = (SB(sy) + (1 << (SABIT - 1))) / pay;
        int n = 0;

        for (int yi = 0; yi < t->yol_sayi && n < 62; yi++) {
            const tv_yol_t *y = &t->yol[yi];
            if (y->katman != katman) continue;
            const tv_nokta_t *p = &t->nokta[y->bas];
            for (int i = 0; i < y->uzunluk && n < 62; i++) {
                const tv_nokta_t *a = &p[i];
                const tv_nokta_t *b = &p[(i + 1) % y->uzunluk];
                int32_t x0 = (int32_t)a->x * boy * (1 << SABIT) / TAMGA_BIRIM;
                int32_t y0 = (int32_t)a->y * boy * (1 << SABIT) / TAMGA_BIRIM;
                int32_t x1 = (int32_t)b->x * boy * (1 << SABIT) / TAMGA_BIRIM;
                int32_t y1 = (int32_t)b->y * boy * (1 << SABIT) / TAMGA_BIRIM;
                if (y0 == y1) continue;
                if (!((y0 <= yy && yy < y1) || (y1 <= yy && yy < y0))) continue;
                int64_t t0 = (int64_t)(yy - y0) * (int64_t)(x1 - x0);
                int32_t xk = x0 + (int32_t)(t0 / (int64_t)(y1 - y0));
                kes[n].x = xk;
                kes[n].yon = (y1 > y0) ? 1 : -1;
                n++;
            }
        }
        if (n < 2) continue;

        /* eklemeli sıralama: kesim sayısı küçük */
        for (int i = 1; i < n; i++) {
            kesim_t k = kes[i]; int j = i - 1;
            while (j >= 0 && kes[j].x > k.x) { kes[j + 1] = kes[j]; j--; }
            kes[j + 1] = k;
        }

        int w = 0; int32_t bas = 0;
        for (int i = 0; i < n; i++) {
            int onc = w; w += kes[i].yon;
            if (onc == 0 && w != 0) bas = kes[i].x;
            else if (onc != 0 && w == 0) {
                int32_t a = bas, b = kes[i].x;
                if (b <= a) continue;
                int pa = a >> SABIT, pb = (b + (1 << SABIT) - 1) >> SABIT;
                if (pa < 0) pa = 0;
                if (pb > boy) pb = boy;
                for (int px = pa; px < pb; px++) {
                    int32_t sol = SB(px), sag = SB(px + 1);
                    int32_t g0 = (a > sol) ? a : sol;
                    int32_t g1 = (b < sag) ? b : sag;
                    if (g1 <= g0) continue;
                    /* piksel içi kaplama: (g1-g0)/256 * 255 / pay */
                    int kat = (int)(((int32_t)(g1 - g0) * 255) >> SABIT) / pay;
                    int yer = (sy / pay) * boy + px;
                    int v = g_kaplama[yer] + kat;
                    g_kaplama[yer] = (uint8_t)(v > 255 ? 255 : v);
                }
            }
        }
    }
}

void tamga_ciz(int x, int y, tamga_id_t id, int boy, uint32_t renk, uint32_t zemin) {
    const tamga_t *t = tamga_al(id);
    if (!t) return;
    if (boy < 8) boy = 8;
    if (boy > TAMGA_AZAMI) boy = TAMGA_AZAMI;

    /* Küçük boyda vektör taramak yerine elle çizilmiş sade maske:
     * 16 pikselin altında ince çizgiler kaplamaya yayılıp lekeleşiyor. */
    if (boy < TAMGA_KUCUK_SINIR) {
        const uint16_t *m = KUCUK[id];
        uint32_t c = renk ? renk : t->palet[TAMGA_KATMAN - 1];
        for (int sy = 0; sy < 16; sy++) {
            uint16_t satir = m[sy];
            for (int sx = 0; sx < 16; sx++) {
                if (!(satir & (1u << (15 - sx)))) continue;
                fb_put_pixel(x + sx, y + sy, c);
            }
        }
        return;
    }

    for (int k = 0; k < TAMGA_KATMAN; k++) {
        katman_tara(t, k, boy);
        uint32_t c = renk ? renk : t->palet[k];
        for (int sy = 0; sy < boy; sy++) {
            for (int sx = 0; sx < boy; sx++) {
                int a = g_kaplama[sy * boy + sx];
                if (a == 0) continue;
                uint32_t zem = (zemin == TAMGA_SAYDAM)
                             ? fb_get_pixel(x + sx, y + sy) : zemin;
                fb_put_pixel(x + sx, y + sy, harman(zem, c, a));
            }
        }
    }
}

void tamga_yuvarlak_kutu(int x, int y, int en, int boy, int yaricap, uint32_t renk) {
    if (yaricap * 2 > en)  yaricap = en / 2;
    if (yaricap * 2 > boy) yaricap = boy / 2;
    int r2 = yaricap * yaricap;
    for (int sy = 0; sy < boy; sy++) {
        for (int sx = 0; sx < en; sx++) {
            int dx = 0, dy = 0;
            if (sx < yaricap)             dx = yaricap - sx;
            else if (sx >= en - yaricap)  dx = sx - (en - yaricap - 1);
            if (sy < yaricap)             dy = yaricap - sy;
            else if (sy >= boy - yaricap) dy = sy - (boy - yaricap - 1);
            if (dx && dy && dx * dx + dy * dy > r2) continue;
            fb_put_pixel(x + sx, y + sy, renk);
        }
    }
}

/* =====================================================================
 * RIHTIM ÖNBELLEĞİ
 * Rıhtımdaki 15 simge her yeniden çizimde vektörden taranıyordu; bu,
 * kare başına 15 x 3 katman x ~128 alt-tarama satırı demek. Ekran
 * görüntüsünde rıhtımın yarısı boş çıkıyordu: çizim yetişmiyordu.
 * Karo + simge birleşimi ilk çizimde önbelleğe alınır, sonrasında
 * doğrudan kopyalanır. Tema değişirse tamga_onbellek_bosalt() çağrılır.
 * ===================================================================== */
#define ONBELLEK_BOY 44

static uint32_t g_onbellek[TAMGA_SAYI][ONBELLEK_BOY * ONBELLEK_BOY];
static uint8_t  g_onbellek_dolu[TAMGA_SAYI];

void tamga_onbellek_bosalt(void) {
    for (int i = 0; i < TAMGA_SAYI; i++) g_onbellek_dolu[i] = 0;
}

void tamga_kutu_onbellekli(int x, int y, tamga_id_t id, uint32_t renk,
                           uint32_t karo_renk) {
    if (id < 0 || id >= TAMGA_SAYI) return;
    if (!g_onbellek_dolu[id]) {
        /* Ekrana çiz, oku, sakla: ayrı bir yazılım tamponu yok. */
        tamga_kutu_ciz(x, y, id, 32, 6, renk, karo_renk);
        for (int j = 0; j < ONBELLEK_BOY; j++)
            for (int i = 0; i < ONBELLEK_BOY; i++)
                g_onbellek[id][j * ONBELLEK_BOY + i] = fb_get_pixel(x + i, y + j);
        g_onbellek_dolu[id] = 1;
        return;
    }
    const uint32_t *p = g_onbellek[id];
    for (int j = 0; j < ONBELLEK_BOY; j++)
        for (int i = 0; i < ONBELLEK_BOY; i++)
            fb_put_pixel(x + i, y + j, p[j * ONBELLEK_BOY + i]);
}

void tamga_kutu_ciz(int x, int y, tamga_id_t id, int boy, int kenar_pay,
                    uint32_t renk, uint32_t karo_renk) {
    const tamga_t *t = tamga_al(id);
    if (!t) return;
    int kutu = boy + kenar_pay * 2;
    /* Karo, simgenin ÜLGEN paletindeki kendi rengidir; okunaklılık için
     * koyultulur. Simgenin kendisi tek renk çizilir (varsayılan turkuaz). */
    /* karo_renk bir TABAN tondur, doğrudan dolgu değil: kenarlık ondan
     * hafif koyultularak, dolgu ise iyice koyultularak türetilir.
     * 0 verilirse tamganın kendi palet rengi taban olur. */
    uint32_t taban = karo_renk ? karo_renk : t->vurgu;
    uint32_t kz = tamga_ton(taban, -185);
    tamga_yuvarlak_kutu(x, y, kutu, kutu, kutu / 5, tamga_ton(taban, -70));
    tamga_yuvarlak_kutu(x + 1, y + 1, kutu - 2, kutu - 2, kutu / 5, kz);
    tamga_ciz(x + kenar_pay, y + kenar_pay, id, boy, renk, kz);
}

void tamga_muhur_ciz(int x, int y, tamga_id_t id, int boy,
                     uint32_t renk, uint32_t zemin) {
    const tamga_t *t = tamga_al(id);
    if (!t) return;
    if (boy < 32) boy = 32;
    if (boy > TAMGA_AZAMI) boy = TAMGA_AZAMI;
    uint32_t cerceve = tema_simdiki()->metalik;
    uint32_t halka   = renk ? renk : t->palet[TAMGA_KATMAN - 1];

    /* Halkalar da kenar yumuşatmalı: yarıçapı 4 kat çözünürlükte
     * örnekleyip kaplama sayıyoruz. Tamsayı; karşılaştırmalar
     * 16 kat büyütülmüş yarıçap kareleri üzerinden yapılır. */
    const int ALT = 4;
    int mrk2 = boy;                        /* 2*merkez, alt-ızgara birimi */
    int dis  = boy - 2, dis_ic = dis - (boy / 24 + 2);
    int ic   = boy - (boy * 2) / 11, ic_ic = ic - 2;

    for (int sy = 0; sy < boy; sy++) {
        for (int sx = 0; sx < boy; sx++) {
            int kap_c = 0, kap_h = 0;
            for (int oy = 0; oy < ALT; oy++) {
                for (int ox = 0; ox < ALT; ox++) {
                    int px = sx * 2 * ALT + ox * 2 + 1;   /* alt-ızgara */
                    int py = sy * 2 * ALT + oy * 2 + 1;
                    int dx = px - mrk2 * ALT, dy = py - mrk2 * ALT;
                    int r2 = dx * dx + dy * dy;
                    int A2 = ALT * ALT;
                    if (r2 <= dis * dis * A2 && r2 >= dis_ic * dis_ic * A2) kap_c++;
                    else if (r2 <= ic * ic * A2 && r2 >= ic_ic * ic_ic * A2) kap_h++;
                }
            }
            int n = ALT * ALT;
            if (kap_c == 0 && kap_h == 0) {
                if (zemin != TAMGA_SAYDAM) {
                    /* mühür içi zemin: yalnız dış halkanın içi */
                    int dx = sx - boy / 2, dy = sy - boy / 2;
                    if (dx * dx + dy * dy < dis_ic * dis_ic) fb_put_pixel(x + sx, y + sy, zemin);
                }
                continue;
            }
            uint32_t zem = (zemin == TAMGA_SAYDAM)
                         ? fb_get_pixel(x + sx, y + sy) : zemin;
            uint32_t c = zem;

            /* --- RÖLYEF ---
             * Işık sol üstten gelir. Halka üzerindeki noktanın merkeze
             * göre yönü (-dx-dy) aydınlığı belirler: sol üst parlar,
             * sağ alt kararır. Böylece düz daire yerine kabartma
             * madalyon izlenimi doğar. Tamsayı; -255..255 aralığı. */
            int dxr = sx - boy / 2, dyr = sy - boy / 2;
            int isik = (-(dxr + dyr) * 255) / (boy / 2 + 1);
            if (isik > 200) isik = 200;
            if (isik < -200) isik = -200;

            if (kap_h) c = harman(c, tamga_ton(halka, isik / 2), kap_h * 255 / n);
            if (kap_c) c = harman(c, tamga_ton(cerceve, isik), kap_c * 255 / n);
            fb_put_pixel(x + sx, y + sy, c);
        }
    }

    int ic_boy = (boy * 3) / 4;
    tamga_ciz(x + (boy - ic_boy) / 2, y + (boy - ic_boy) / 2, id, ic_boy, renk,
              zemin == TAMGA_SAYDAM ? TAMGA_SAYDAM : zemin);
}
