typedef struct { const orb_glif_t *g; int n; const uint8_t *v; int satir; } orb_kume_t;

static orb_kume_t kume(int kucuk) {
    orb_kume_t k;
    if (kucuk) { k.g = GLIF_K; k.n = (int)(sizeof(GLIF_K)/sizeof(GLIF_K[0]));
                 k.v = VERI_K; k.satir = ORB_K_SATIR; }
    else       { k.g = GLIF_B; k.n = (int)(sizeof(GLIF_B)/sizeof(GLIF_B[0]));
                 k.v = VERI_B; k.satir = ORB_B_SATIR; }
    return k;
}

int orb_satir_yuksekligi(int kucuk) { return kume(kucuk).satir; }

static const orb_glif_t *bul(orb_kume_t k, uint32_t kod) {
    for (int i = 0; i < k.n; i++) if (k.g[i].kod == kod) return &k.g[i];
    for (int i = 0; i < k.n; i++) if (k.g[i].kod == '?') return &k.g[i];
    return 0;
}

int orb_en(const char *s, int kucuk) {
    orb_kume_t k = kume(kucuk);
    int en = 0; const char *p = s;
    while (*p) { const orb_glif_t *g = bul(k, fb_utf8_kod(&p)); if (g) en += g->ilerle; }
    return en;
}

static uint32_t hrm(uint32_t z, uint32_t o, int a) {
    if (a >= 15) return o;
    if (a <= 0)  return z;
    int zr=(int)((z>>16)&0xFF), zg=(int)((z>>8)&0xFF), zb=(int)(z&0xFF);
    int orr=(int)((o>>16)&0xFF), og=(int)((o>>8)&0xFF), ob=(int)(o&0xFF);
    return ((uint32_t)((zr*(15-a)+orr*a)/15)<<16)
         | ((uint32_t)((zg*(15-a)+og *a)/15)<<8)
         |  (uint32_t)((zb*(15-a)+ob *a)/15);
}

void orb_yaz(int x, int y, const char *s, uint32_t renk, int golge, int kucuk) {
    orb_kume_t k = kume(kucuk);
    const char *p = s;
    while (*p) {
        const orb_glif_t *g = bul(k, fb_utf8_kod(&p));
        if (!g) continue;
        const uint8_t *m = &k.v[g->ofset];
        for (int j = 0; j < k.satir; j++)
            for (int i = 0; i < g->en; i++) {
                int a = m[j * g->en + i];
                if (a == 0) continue;
                if (golge)
                    fb_put_pixel(x+i+1, y+j+1,
                                 hrm(fb_get_pixel(x+i+1, y+j+1), 0x041018u, a));
                fb_put_pixel(x+i, y+j, hrm(fb_get_pixel(x+i, y+j), renk, a));
            }
        x += g->ilerle;
    }
}

void orb_yaz_ortali(int orta_x, int y, const char *s, uint32_t renk, int golge, int kucuk) {
    orb_yaz(orta_x - orb_en(s, kucuk) / 2, y, s, renk, golge, kucuk);
}

/* Verilen genisligi asmayacak sekilde kirpip ortalar. Rihtim hucresi
 * 75 piksel; "Yetkilendirme" gibi uzun roller komsuya tasiyordu. */
void orb_yaz_ortali_sinirli(int orta_x, int y, const char *s, uint32_t renk,
                            int golge, int kucuk, int azami_en) {
    char gec[48];
    int n = 0;
    while (s[n] && n < (int)sizeof(gec) - 1) n++;
    for (int i = 0; i < n; i++) gec[i] = s[i];
    gec[n] = 0;
    while (n > 1 && orb_en(gec, kucuk) > azami_en) {
        n--;
        /* UTF-8 ortasindan kesme: devam baytini da at */
        while (n > 1 && ((unsigned char)gec[n] & 0xC0) == 0x80) n--;
        gec[n] = 0;
    }
    orb_yaz_ortali(orta_x, y, gec, renk, golge, kucuk);
}

/* Metni en cok iki satira sarar ve ortalar. Bosluk varsa oradan boler
 * ("DEDE KORKUT" -> "DEDE" / "KORKUT"); tek kelime sigmazsa kirpar.
 * Donen deger yazilan satir sayisidir. */
int orb_yaz_ortali_sar(int orta_x, int y, const char *s, uint32_t renk,
                       int golge, int kucuk, int azami_en, int satir_ara) {
    if (orb_en(s, kucuk) <= azami_en) {
        orb_yaz_ortali(orta_x, y, s, renk, golge, kucuk);
        return 1;
    }
    /* sigmayan metinde son bosluktan bol */
    int n = 0; while (s[n]) n++;
    int bol = -1;
    for (int i = 0; i < n; i++) if (s[i] == ' ') { bol = i; break; }
    if (bol < 0) {
        orb_yaz_ortali_sinirli(orta_x, y, s, renk, golge, kucuk, azami_en);
        return 1;
    }
    char a[32], b[32];
    int i;
    for (i = 0; i < bol && i < 31; i++) a[i] = s[i];
    a[i] = 0;
    int j = 0;
    for (i = bol + 1; s[i] && j < 31; i++) b[j++] = s[i];
    b[j] = 0;
    orb_yaz_ortali_sinirli(orta_x, y, a, renk, golge, kucuk, azami_en);
    orb_yaz_ortali_sinirli(orta_x, y + satir_ara, b, renk, golge, kucuk, azami_en);
    return 2;
}
